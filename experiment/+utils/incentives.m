function out = incentives(action, varargin)
%UTILS.INCENTIVES  Toggleable payment module.
%
%   cfg  = utils.incentives('config')
%   txt  = utils.incentives('instructions', domain, cfg)
%   bonus = utils.incentives('compute', sess, dataMat, cfg)

switch lower(char(action))

case 'config'
    out.enabled      = false;   % master switch
    out.showRunning  = false;   % running total during trials -- see below
    out.showAtBreaks = true;    % running total between blocks (safe)
    out.basePayment  = 10.00;   % guaranteed, for showing up
    out.bonusMin     = 0.00;
    out.bonusMax     = 10.00;
    % Anchor-relative: unit is bonus dollars per 1.0 of surplus/anchor; re-check against real payouts before enabling.
    out.houseScale   = 20.0;
    out.wageScale    = 12.0;
    out.currency     = 'USD';
    % showRunning defaults off: a live counter on the trial screen pulls gaze from the stimuli.
    return

case 'instructions'
    domain = varargin{1};
    cfg    = varargin{2};
    isHouse = strcmpi(domain, 'houses');

	    if ~cfg.enabled
	        if isHouse
	            out = ['In this task you will search for a house to buy.\n\n' ...
	                   'Options will appear and disappear as they come on and off ' ...
	                   'the market. Left-click an option to inspect it. Right-click ' ...
	                   'an option to reject it and remove it from the market.\n\n' ...
	                   'In the detail view, left-click to make an offer or right-click ' ...
	                   'to go back. On the offer screen, right-click cancels and returns ' ...
	                   'you to the market.\n\n' ...
	                   'You are bidding against other buyers. If your offer wins, ' ...
	                   'you pay what it took to beat the next best offer -- not the ' ...
	                   'amount you offered. So there is nothing to gain by offering ' ...
	                   'less than the house is worth to you.\n\n' ...
	                   'How much it takes to win depends on how competitive the ' ...
	                   'market is, which is shown with each market. When competition ' ...
	                   'is high, the listed price is often not enough.\n\n' ...
	                   'Please treat each decision as though the money were real.'];
	        else
	            out = ['In this task you will search for a job.\n\n' ...
	                   'Openings will appear and disappear as they are posted and ' ...
	                   'filled. Left-click an opening to inspect it. Right-click an ' ...
	                   'opening to reject it and remove it from the market.\n\n' ...
	                   'In the detail view, left-click to name your salary requirement ' ...
	                   'or right-click to go back. On the wage screen, right-click ' ...
	                   'cancels and returns you to the market.\n\n' ...
	                   'Please treat each decision as though the job were real.'];
	        end
	    else
	        if isHouse
	            out = sprintf([ ...
	                'In this task you will search for a house to buy.\n\n' ...
	                'Options appear and disappear as they come on and off the market. ' ...
	                'Left-click an option to inspect it. Right-click an option to reject ' ...
	                'it and remove it from the market. In the detail view, left-click to ' ...
	                'make an offer or right-click to go back. On the offer screen, ' ...
	                'right-click cancels and returns you to the market.\n\n' ...
	                'YOUR PAYMENT\n' ...
	                'You are guaranteed $%.2f for taking part.\n\n' ...
                'At the end, ONE of your successful purchases will be chosen at ' ...
                'random. If you bought that house for less than it was worth, you ' ...
                'earn a bonus based on the difference, up to $%.2f.\n\n' ...
                'You are bidding against other buyers. If your offer wins, you ' ...
                'pay what it took to beat the next best offer -- not the amount ' ...
                'you offered. So it is in your interest to offer what the house ' ...
                'is worth to you: offering less only costs you the house, and ' ...
                'offering more never costs you more than you win it for.\n\n' ...
                'How much it takes to win depends on how competitive the market ' ...
                'is, which is shown with each market. When competition is high, ' ...
                'the listed price is often not enough.'], ...
                cfg.basePayment, cfg.bonusMax);
        else
	            out = sprintf([ ...
	                'In this task you will search for a job.\n\n' ...
	                'Openings appear and disappear as they are posted and filled. ' ...
	                'Left-click an opening to inspect it. Right-click an opening to ' ...
	                'reject it and remove it from the market. In the detail view, ' ...
	                'left-click to name your salary requirement or right-click to go ' ...
	                'back. On the wage screen, right-click cancels and returns you to ' ...
	                'the market.\n\n' ...
	                'YOUR PAYMENT\n' ...
                'You are guaranteed $%.2f for taking part.\n\n' ...
                'At the end, ONE of the jobs you accepted will be chosen at ' ...
                'random. The more that job pays above the minimum wage you told ' ...
                'us you would accept, the larger your bonus, up to $%.2f.\n\n' ...
                'This means it is in your interest to ask for the most you think ' ...
                'the employer will agree to -- but if you ask too much, they will ' ...
                'withdraw the offer and you move on with nothing from that job.'], ...
                cfg.basePayment, cfg.bonusMax);
        end
    end
    return

case 'compute'
    sess = varargin{1};
    dataMat = varargin{2};
    cfg = varargin{3};

    out = struct('enabled', cfg.enabled, 'base', 0, 'bonus', 0, 'total', 0, ...
                 'selectedTrial', [], 'surplus', NaN, 'surplusFrac', NaN, ...
                 'explanation', '');

    if ~cfg.enabled
        out.explanation = 'No performance payment in this version.';
        return
    end

    out.base = cfg.basePayment;

    wins = utils.collectWins(dataMat);      % see helper below
    if isempty(wins)
        out.total = out.base;
        out.explanation = sprintf(['You did not complete any successful ' ...
            'acquisitions, so there is no bonus. Your payment is $%.2f.'], out.base);
        return
    end

    pick = wins(randi(numel(wins)));
    out.selectedTrial = pick;

    if strcmpi(pick.domain, 'houses')
        out.surplus = pick.trueValue - pick.pricePaid;
        base = pick.anchor;
        raw = (out.surplus / base) * cfg.houseScale;
    else
        out.surplus = pick.wageObtained - pick.reservationWage;
        base = pick.reservationWage;
        raw = (out.surplus / base) * cfg.wageScale;
    end
    if ~isfinite(base) || base <= 0
        % No usable anchor: pay the base rather than a divide-by-zero bonus.
        raw = 0;
    end

    out.bonus = min(max(raw, cfg.bonusMin), cfg.bonusMax);
    out.total = out.base + out.bonus;
    out.surplusFrac = out.surplus / base;
    out.explanation = sprintf([ ...
        'Randomly selected: %s, trial %d.\n' ...
        'Surplus: %s\nBonus: $%.2f\nTotal payment: $%.2f'], ...
        pick.domain, pick.trial, ...
        utils.formatCurrency(out.surplus, ...
            utils.ternary(strcmpi(pick.domain,'houses'), 'total', 'hourly')), ...
        out.bonus, out.total);
    return

otherwise
    error('hw:incentives:badAction', 'Unknown action "%s".', action);
end

end
